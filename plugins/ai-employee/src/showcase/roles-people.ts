import type { Board, Role, Source } from './types';

type RowSeed = [id: string, cells: string[], detail: string, sourceId?: string];
type BoardSeed = Omit<Board, 'rows'> & { rows: RowSeed[] };

function board(seed: BoardSeed): Board {
  return { ...seed, rows: seed.rows.map(([id, cells, detail, sourceId = 'source-1']) => ({ id, cells, detail, sourceId })) };
}

function sources(area: string, entries: [string, string, string][]): Source[] {
  return entries.map(([name, type, content], i) => ({
    id: `source-${i + 1}`, name, type, collectedAt: '2026-10-09 09:00',
    origin: `${area} / 本地虚构演示资料`, content,
  }));
}

