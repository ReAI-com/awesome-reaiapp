const REGISTERED: ReadonlySet<string> = new Set<string>([
  ...matrix.stableErrors,
  ...matrix.pluginPermissions.stableErrors,
  ...hostCodes.codes,
  ...PLUGIN_AND_HOST_CODES,
]);
const PLUGIN_NAMESPACE = "com.reai.voice/";
/** 回听的 MediaError 只有 1–4 四个标准码。 */
const MEDIA_ERROR = /^MediaError code [1-4]$/;

/** 登记过的码原样返回；其余（含形似码的凭据、用户说的话）一律 undefined。 */
export function registeredErrorCode(value: unknown): string | undefined {
  if (typeof value !== "string") return undefined;
  const code = value.trim();
  if (REGISTERED.has(code) || MEDIA_ERROR.test(code)) return code;
  if (code.startsWith(PLUGIN_NAMESPACE) && REGISTERED.has(code.slice(PLUGIN_NAMESPACE.length))) return code;
  return undefined;
}
