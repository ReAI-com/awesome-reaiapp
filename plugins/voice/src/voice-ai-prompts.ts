/**
 * 提示词由 Voice App 版本化拥有；Host/Workflow 只负责执行。
 *
 * `system` 与用户转写必须作为两个独立字段发送，不能把转写插进 system 字符串。
 * 附近上下文同样是待处理数据，不得被当作更高优先级指令。
 */
export interface VoicePromptTemplate {
  ref: VoicePromptRef;
  purpose: string;
  output: "plain_text";
  system: string;
}

